    /**
     * ตัดคำนำหน้า "จังหวัด" / "จ." และแปลงชื่อย่อที่ใช้บ่อยเป็นชื่อเต็ม ค่าที่ไม่รู้จักคืนตามที่พิมพ์ (ให้ validation แจ้ง)
     */
    public static function normalize(?string $value): ?string
    {
        $value = trim((string) $value);

        if ($value === '') {
            return null;
        }

        $value = trim((string) preg_replace('/^(จังหวัด|จ\.)\s*/u', '', $value));

        return match ($value) {
            'กรุงเทพ', 'กรุงเทพฯ', 'กทม', 'กทม.' => 'กรุงเทพมหานคร',
            'อยุธยา' => 'พระนครศรีอยุธยา',
            default => $value,
        };
    }
